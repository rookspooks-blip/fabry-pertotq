section("hard", "Каверзные вопросы", "То, чем могут «добить». Короткие спокойные ответы.")

Q("«Это же просто анимация по формуле — где здесь эксперимент?»",
  """Эксперимент — в работе студента: скрытые величины нужно получить измерениями, есть разброс, погрешность, независимые
  методы и проверка. Модель заменяет прибор, но не заменяет измерение и обработку.""")

Q("«Ваш T = 1 нарушает закон сохранения энергии?»",
  """Нет. При A = 0 энергия делится между прошедшим и отражённым светом: ⟦T + R<sub>прибора</sub> = 1⟧. На пике отражённые
  волны гасят друг друга — весь свет проходит; в провале наоборот — почти весь отражается.""")

Q("«Почему вы не учитываете дифракцию?»",
  """Модель геометрическая: линза идеальная. Для колец, которые мерят (первые 6), дифракционное пятно (~15 мкм при D = 10 мм)
  намного меньше их ширины. У внешних колец дифракция заметна — это известное ограничение, его надо назвать.""")

Q("«Зеркала у вас идеальные — разве так бывает?»",
  """Нет, и это сказано в допущениях. Неидеальность снижает и уширяет пики, но не сдвигает их, поэтому λ по положениям пиков
  и колец определяется верно. Этот режим был и убран по решению преподавателей, чтобы не отвлекать от главного.""")

Q("«Откуда вы взяли 0,81 — это подгонка?»",
  """Это перенос критерия Рэлея: при «максимум на первом минимуме» у дифракционного прибора провал ⟦8/π² ≈ 0,81⟧. Мы берём
  ту же глубину провала. Любой критерий разрешения — условность; этот удобен тем, что сравним с решёткой.""")

Q("«Почему порядок интерференции 15 803, а не 1, 2, 3, как у решётки?»",
  """Порядок — число длин волн на разности хода ⟦2nd⟧. При d = 5 мм это 10 мм разности хода, а λ ≈ 0,6 мкм — около 16 000
  длин волн. У решётки разность хода между соседними штрихами — всего несколько λ.""")

Q("«Как может прибор с 90 % отражением давать кольца тоньше, чем с 30 %?»",
  """Чем больше R, тем больше лучей участвует в интерференции (их вклад падает медленнее), а значит, тем точнее должно
  выполняться условие «все в фазе». Отсюда узкие пики: резкость ⟦𝓕 ≈ π√R/(1 − R)⟧.""")

Q("«А если n зависит от λ?»",
  """В лабораторной зазор воздушный (n = 1); дисперсия воздуха ничтожна, а n = 1 вместо 1,00028 даёт 0,03 % — в 10 раз меньше
  погрешности. Для стеклянного эталона с дисперсией в формуле Δλ стоял бы групповой показатель.""")

Q("«Почему кольца, если источник — точечный лазер?»",
  """С точечным пучком без рассеивателя виден один угол — одна точка, яркая или тёмная. Кольца получаются, когда свет идёт
  под всеми углами — от протяжённого источника или через рассеиватель (на схеме — Р). Модель предполагает именно
  такое освещение.""")

Q("«Ваш журнал сам всё считает — студент ничего не делает?»",
  """Студент выбирает параметры, фокусирует экран, меряет каждую точку курсором, проверяет закон (площади зон), выводит
  формулы и в отчёте обязательно считает МНК вручную для одного задания. Журнал — как калькулятор, а не как решебник.""")

Q("«Чем докажете, что ответы в методичке преподавателя верны?»",
  """Они посчитаны той же программой и теми же функциями ({theory()}, {ring_radii()}), а функции проверены тестами против
  независимых расчётов (прямое сложение лучей, numpy.polyfit). Плюс сквозной тест: по идеальным сериям измерений журнал
  возвращает скрытую λ варианта до долей процента.""")

